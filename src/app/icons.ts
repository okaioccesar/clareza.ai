export type IconName = keyof typeof paths;

export function svg(name: IconName | string): string {
  const body = paths[name as IconName] ?? paths.file;
  return `<svg class="icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

export const icon = (name: IconName): Raw => raw(svg(name));

/** Fills every `[data-icon]` placeholder inside `root`. */
export function hydrateIcons(root: ParentNode = document) {
  root.querySelectorAll<HTMLElement>('[data-icon]').forEach((element) => {
    if (!element.firstElementChild) element.innerHTML = svg(element.dataset.icon!);
  });
}
